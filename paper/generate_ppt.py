def add_title_content_slide(prs, title, content):
    layout = prs.slide_layouts[5]  # Title Only
    slide = prs.slides.add_slide(layout)

    # Title
    title_box = slide.shapes.title
    title_box.text = title
    title_tf = title_box.text_frame
    title_tf.paragraphs[0].font.size = Pt(34)
    title_tf.paragraphs[0].font.bold = True
    title_tf.paragraphs[0].font.color.rgb = RGBColor(0x12, 0x2B, 0x55)

    # Content textbox
    left = Inches(0.8)
    top = Inches(1.6)
    width = Inches(12.0 - 1.6)
    height = Inches(7.5 - 2.0)

    box = slide.shapes.add_textbox(left, top, width, height)
    tf = box.text_frame
    tf.clear()

    p = tf.paragraphs[0]
    p.text = content
    p.font.size = Pt(18)
    p.font.name = "Microsoft YaHei"
    p.line_spacing = 1.15

    return slide

def add_cover(prs):
    slide = prs.slides.add_slide(prs.slide_layouts[0])  # Title Slide
    slide.shapes.title.text = TITLE
    slide.placeholders[1].text = SUBTITLE + "\n\n汇报人：XXX\n时间：202X年X月"

    # Format
    t = slide.shapes.title.text_frame.paragraphs[0]
    t.font.size = Pt(34)
    t.font.bold = True
    t.font.color.rgb = RGBColor(0x12, 0x2B, 0x55)

    st = slide.placeholders[1].text_frame
    for i, p in enumerate(st.paragraphs):
        p.font.size = Pt(18)
        p.font.name = "Microsoft YaHei"
    return slide

def main():
    prs = Presentation()
    prs.slide_width = Inches(13.33)   # 16:9
    prs.slide_height = Inches(7.5)

    # Cover from slide 1 content block
    add_cover(prs)

    # Remaining slides
    for idx, (title, content) in enumerate(slides[1:], start=2):
        add_title_content_slide(prs, f"{idx}/12  {title}", content)

    prs.save("大数据伦理_中国制造_一带一路_职业规划.pptx")
    print("Generated: 大数据伦理_中国制造_一带一路_职业规划.pptx")

if __name__ == "__main__":
    main()